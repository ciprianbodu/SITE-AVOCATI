function practiceBySlug(string $slug, string $lang = 'ro'): ?array
{
    foreach (practiceCatalog() as $roSlug => $item) {
        if ($lang === 'ro' && $roSlug === $slug) {
            return $item + ['slug' => $roSlug, 'lang' => 'ro', 'copy' => $item['ro']];
        }
        if ($lang === 'en' && $item['en'] === $slug) {
            return $item + ['slug' => $roSlug, 'enSlug' => $item['en'], 'lang' => 'en', 'copy' => $item['en_copy']];
        }
    }
    return null;
}

